<?php
declare(strict_types=1);
require __DIR__.'/Support/OemDisposable.php';
require __DIR__.'/Support/OemFixtures.php';
use think\facade\Db;
use app\common\service\brand\BrandWorkflowService as Flow;
use app\common\service\brand\TenantBrandService as Brand;
oemCheck(method_exists(Flow::class,'review'),'Seller review and submission workflow is missing');
Db::startTrans();
try {
    $f=oemFixture();
    $logoId=Db::name('tenant_file')->insertGetId(['tenant_id'=>$f['seller'],'type'=>10,'name'=>'owned-logo.png','uri'=>'uploads/oem-fixture/logo.png','source'=>1,'source_id'=>$f['user'],'storage_scope'=>'platform','storage_engine'=>'local','create_time'=>time()]);
    oemReject(fn()=>Brand::createBrandOrder($f['seller'],$f['user']+1,4,array_replace($f['params'],['logo'=>'uploads/oem-fixture/logo.png','logo_id'=>$logoId])),'logo from another customer accepted');
    $first=Brand::createBrandOrder($f['seller'],$f['user'],4,$f['params']); $id=$first['order_id'];
    oemReject(fn()=>Flow::review($f['seller'],9,$id,'approve',''),'unpaid order reviewed');
    oemPaid($f,$id);
    oemReject(fn()=>Flow::review($f['seller']+1,9,$id,'approve',''),'cross-seller review');
    Flow::review($f['seller'],9,$id,'needs_info','请补充联系邮箱');
    oemReject(fn()=>Flow::supplement($f['seller'],$f['user']+1,$id,['contact'=>'mail@example.test']),'cross-user supplement');
    Flow::supplement($f['seller'],$f['user'],$id,['contact'=>'mail@example.test']);
    $history=json_decode((string)Db::name('tenant_brand_event')->where(['order_id'=>$id,'action'=>'supplement'])->value('payload'),true);
    oemCheck(is_array($history) && $history['before']['contact']==='13300000000' && $history['after']['contact']==='mail@example.test','brand supplement history retains original and new information');
    oemCheck(Flow::owned($f['seller'],$f['user'],$id)['workflow_state']==='tenant_review','supplement returns to seller review');
    Flow::review($f['seller'],9,$id,'approve','审核通过');
    oemCheck(Flow::owned($f['seller'],$f['user'],$id)['workflow_state']==='awaiting_quota','zero inventory waits procurement');
    oemReject(fn()=>Flow::submit($f['seller'],9,$id),'no reservation submitted to platform');
    Db::name('tenant')->where('id',$f['seller'])->update(['oem_flow_enabled'=>2,'oem_sales_enabled'=>0]);
    $purchase=Flow::createQuota($f['seller'],9,4,0,1,$id);
    $samePurchase=Flow::createQuota($f['seller'],9,4,0,1,$id);
    oemCheck($purchase['order_id']===$samePurchase['order_id'],'linked purchase retries restore the same unpaid procurement order');
    oemCheck($purchase['order_amount']==='19.99','linked purchase retains original procurement snapshot after entry closure');
    oemPaid($f,$purchase['order_id'],Brand::FROM_QUOTA);
    oemCheck((int)Flow::owned($f['seller'],$f['user'],$id)['reserve_status']===1,'linked procurement reserves approved order');
    Flow::reserve($f['seller'],9,$id);
    Flow::review($f['seller'],9,$id,'approve','重复审核');
    oemCheck((int)Db::name('tenant_brand_quota_bucket')->where('tenant_id',$f['seller'])->value('reserved_quota')===1,'repeated reservation stays once');
    Flow::submit($f['seller'],9,$id);
    $events=Db::name('tenant_brand_event')->where(['order_id'=>$id,'action'=>'submit'])->count();
    Flow::submit($f['seller'],9,$id);
    oemCheck(Db::name('tenant_brand_event')->where(['order_id'=>$id,'action'=>'submit'])->count()===$events,'submission is idempotent');
    oemCheck(Flow::owned($f['seller'],$f['user'],$id)['workflow_state']==='platform_review','platform approval still required');
    oemCheck(Db::name('tenant_brand_job')->where('order_id',$id)->count()===0,'seller submission does not start worker');
    Db::name('tenant')->where('id',$f['seller'])->update(['oem_flow_enabled'=>1,'oem_sales_enabled'=>1]);
    $rejected=Brand::createBrandOrder($f['seller'],$f['user'],4,$f['params']);
    oemPaid($f,$rejected['order_id']);
    Flow::review($f['seller'],9,$rejected['order_id'],'reject','资料无法通过审核');
    $row=Flow::owned($f['seller'],$f['user'],$rejected['order_id']);
    oemCheck($row['workflow_state']==='refunding' && (int)$row['refund_status']===2,'rejection enters confirmed-result refund workflow');
    oemCheck(Db::name('tenant_brand_refund')->where('order_id',$rejected['order_id'])->count()===1,'rejection queues original full refund once');
    oemCheck((int)$row['reserve_status']!==3,'refund request alone never releases quota');
    echo "PASS real seller review, supplement, linked procurement, reservation, submission and rejection\n";
} finally { Db::rollback(); }
