<?php
/** Local integration test: no upstream calls; all database fixtures are rolled back. */
require dirname(__DIR__) . '/vendor/autoload.php';
(new \think\App(dirname(__DIR__) . '/'))->initialize();
set_exception_handler(static function (Throwable $e): void { fwrite(STDERR, $e->getMessage()."\n".$e->getTraceAsString()."\n"); exit(1); });
use think\facade\Db;
use app\common\model\power\PowerMarketProduct as Product;
use app\common\model\power\PowerMarketSku as Sku;
use app\common\model\power\TenantPowerMarketSkuPrice as TenantPrice;
use app\common\model\app\aigc_digital_human\AigcDigitalHumanConfig as Config;
use app\common\model\app\aigc_digital_human\AigcDigitalHumanBilling as Billing;
use app\common\model\app\aigc_digital_human\AigcDigitalHumanVoice as Voice;
use app\common\model\tenant\Tenant;
use app\common\model\user\User;
use app\common\service\app\aigc_digital_human\VoiceCloneMarketPricingService as Market;
use app\common\service\app\aigc_digital_human\AigcDigitalHumanPricingService as Pricing;
use app\common\service\app\aigc_digital_human\AigcDigitalHumanService as Digital;
function check($ok, string $message): void { if (!$ok) throw new RuntimeException($message); echo "PASS $message\n"; }
function rejected(callable $fn, string $message): void { try { $fn(); } catch (\Throwable $e) { echo "PASS $message: ".$e->getMessage()."\n"; return; } throw new RuntimeException($message); }
$c=config('database.connections.mysql');
if (getenv('AIGC_LOCAL_BILLING_TEST') !== '1' || $c['hostname'] !== '127.0.0.1' || $c['database'] !== 'x_cn') throw new RuntimeException('Local opt-in required');
$audio=dirname(__DIR__).'/public/voice-price-test-'.bin2hex(random_bytes(8)).'.wav';
Db::startTrans();
try {
    $tenant=1;
    $product=Product::where(['upstream_app_code'=>'voice_tts','upstream_api_code'=>'clone_voice'])->findOrEmpty();
    if ($product->isEmpty()) throw new RuntimeException('Sync the local voice clone market fixture first');
    Product::where(['upstream_app_code'=>'voice_tts','upstream_api_code'=>'clone_voice'])->update(['status'=>0]);
    Product::where('id',$product['id'])->update(['status'=>1]);
    $product=Product::find($product['id']);
    $sku=Sku::where('product_id',$product['id'])->findOrEmpty();
    Sku::where('product_id',$product['id'])->update(['sale_status'=>0]);
    $sku=Sku::find($sku['id']);
    $sku->save(['sale_points'=>200,'usage_unit'=>'per_call','usage_unit_size'=>1,'status'=>1,'sale_status'=>1,'locked_params'=>[]]);
    TenantPrice::where(['tenant_id'=>$tenant,'sku_id'=>$sku['id']])->delete();
    $tenantConfig=Config::where('tenant_id',$tenant)->findOrEmpty();
    $json=$tenantConfig->isEmpty()?[]:($tenantConfig['config_json']??[]);
    $json['pricing']['voice_clone']=['platform_unit_cost'=>1,'tenant_unit_price'=>2];
    if ($tenantConfig->isEmpty()) $tenantConfig=Config::create(['tenant_id'=>$tenant,'config_json'=>$json]); else $tenantConfig->save(['config_json'=>$json]);
    check((float)Market::quote($tenant)['tenant_cost_points']===200.0,'market cost replaces legacy one point');
    check((float)Market::quote($tenant)['user_charge_points']===200.0,'legacy price below cost uses market default');
    check((float)Pricing::config(0)['voice_clone']['platform_unit_cost']===200.0,'platform pricing is market backed');
    Pricing::savePlatform(['voice_clone'=>['platform_unit_cost'=>1,'tenant_unit_price'=>2]]);
    check((float)Market::quote(0)['tenant_cost_points']===200.0,'legacy platform price writes cannot override market');
    $tenantPrice=TenantPrice::create(['tenant_id'=>$tenant,'sku_id'=>$sku['id'],'sale_points'=>230,'sale_status'=>1]);
    check((float)Market::quote($tenant)['user_charge_points']===230.0,'tenant market default applies');
    Pricing::saveTenant($tenant,['voice_clone'=>['tenant_unit_price'=>260]]);
    check((float)Market::quote($tenant)['user_charge_points']===260.0,'tool user-price override applies');
    check((float)Market::quote(987654321)['user_charge_points']===200.0,'tenant override is isolated');
    rejected(fn()=>Pricing::saveTenant($tenant,['voice_clone'=>['tenant_unit_price'=>199]]),'below-cost override rejected');
    rejected(fn()=>Market::quote($tenant,['expected_clone_price'=>2]),'stale client price rejected');
    $tenantPrice->save(['sale_status'=>0]);
    check(Market::config($tenant)['available']===false,'tenant delisting disables clone quote');
    rejected(fn()=>Market::quote($tenant),'delisted quote fails closed');
    check(isset(Pricing::estimateAvatar($tenant,'aigc_digital_human')['user_charge_points']),'voice outage does not block avatar pricing');
    $tenantPrice->save(['sale_status'=>1]);
    $sku->save(['usage_unit'=>'input_second']);
    rejected(fn()=>Market::quote($tenant),'unsupported billing unit cannot masquerade as fixed price');
    $sku->save(['usage_unit'=>'per_call']);
    $extra=$sku->toArray(); unset($extra['id']); $extra['sku_key']='voice-price-test-'.bin2hex(random_bytes(4));
    $duplicate=Sku::create($extra);
    rejected(fn()=>Market::quote($tenant),'ambiguous market SKUs fail closed');
    $duplicate->delete();
    $sku->save(['sale_points'=>300]);
    check((float)Market::quote($tenant)['user_charge_points']===300.0,'market increase invalidates under-cost tool override');
    $sku->save(['sale_points'=>200]);
    $user=User::create(['tenant_id'=>$tenant,'account'=>'voice_test_'.bin2hex(random_bytes(6)),'nickname'=>'voice price fixture','user_money'=>1000,'sn'=>random_int(10000000,99999999),'create_time'=>time(),'update_time'=>time()]);
    $uid=(int)$user['id'];
    // One second of silent PCM, local-only, so duration validation never accesses a network.
    $pcm=str_repeat("\0",16000);
    file_put_contents($audio,'RIFF'.pack('V',36+strlen($pcm)).'WAVEfmt '.pack('VvvVVvv',16,1,1,8000,16000,2,16).'data'.pack('V',strlen($pcm)).$pcm);
    $params=['name'=>'test voice','audio_uri'=>'/'.basename($audio),'expected_clone_price'=>260];
    Tenant::where('id',$tenant)->update(['point_balance'=>10000]);
    $row=Digital::saveVoice($tenant,$uid,$params);
    check((float)User::find($uid)['user_money']===740.0,'user charged accepted tool price');
    check((float)Tenant::find($tenant)['point_balance']===9800.0,'tenant charged market cost');
    $bills=Billing::where(['tenant_id'=>$tenant,'user_id'=>$uid,'billing_type'=>'voice_clone']);
    $bill=$bills->find();
    check((int)$bill['extra_json']['pricing_snapshot']['market_sku_id']===(int)$sku['id'],'bill records market SKU snapshot');
    $sku->save(['sale_points'=>400]);
    $same=Digital::saveVoice($tenant,$uid,$params);
    check($same['id']===$row['id'] && (float)User::find($uid)['user_money']===740.0,'duplicate request returns original voice without repricing or charging');
    Digital::saveVoice($tenant,$uid,['id'=>$row['id'],'name'=>'renamed']);
    check((float)User::find($uid)['user_money']===740.0,'editing remains free');
    $refund=new ReflectionMethod(Digital::class,'refundCloneBilling'); $refund->setAccessible(true);
    check($refund->invoke(null,$tenant,$uid,'voice_clone',0,(int)$row['id'],'fixture failure')==='','failure refund succeeds');
    $refund->invoke(null,$tenant,$uid,'voice_clone',0,(int)$row['id'],'duplicate failure');
    check((float)User::find($uid)['user_money']===1000.0 && (float)Tenant::find($tenant)['point_balance']===10000.0,'refund uses original amounts exactly once after market price changes');
    check(Billing::find($bill['id'])['billing_status']==='refunded','refund is traceable on original bill');
    Voice::where('id',$row['id'])->update(['status'=>'failed']);
    Tenant::where('id',$tenant)->update(['point_balance'=>0]);
    rejected(fn()=>Digital::saveVoice($tenant,$uid,array_merge($params,['expected_clone_price'=>400])),'insufficient tenant points block creation');
    Tenant::where('id',$tenant)->update(['point_balance'=>10000]);
    User::where('id',$uid)->update(['user_money'=>0]);
    rejected(fn()=>Digital::saveVoice($tenant,$uid,array_merge($params,['expected_clone_price'=>400])),'insufficient user points block creation');
    check(Voice::where(['tenant_id'=>$tenant,'user_id'=>$uid])->count()===1,'failed prechecks leave no orphan voices');
    $product->save(['status'=>0]);
    rejected(fn()=>Market::quote($tenant),'missing active product cannot use legacy defaults');
    echo "PASS voice market integration\n";
} finally { Db::rollback(); if (is_file($audio)) unlink($audio); echo "All fixtures rolled back; no upstream calls\n"; }
